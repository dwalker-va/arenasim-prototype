//! The PINNED catalogue the snapshot harnesses draw: the items, abilities and
//! talents that existed when the snapshots were last pinned (AS-456), read
//! from the live tables but restricted to these members.
//!
//! A snapshot pins LAYOUT. A grid, a count line ("N / total items"), a
//! sibling list or a search result over the LIVE catalogue grows with every
//! content card, so every card that added an item, an ability, an aura or a
//! talent re-blessed the same PNGs, and any two such cards conflicted in them.
//! Drawn over these members instead, content added after AS-456 moves no
//! pixel. What content exists is checked by content tests (set equality over
//! the live tables), never by pixels.
//!
//! The VALUES are still the live ones: a change to a pinned member's name,
//! numbers or text shows in the pages that draw it, as it should. The engine
//! auras are pinned twice over: only the families in [`ENGINE_AURAS`] are
//! listed, and each lists only the auras of a source these tables hold
//! (`encyclopedia::engine_auras`), so a new trinket's buff stays out as well
//! as a new family.
//!
//! These lists are frozen, not maintained: a card adding content does not
//! touch them. Edit one only to re-pin deliberately (a snapshot that needs a
//! member added since), or when a member is deleted from the game.

use arenasim::states::encyclopedia::EngineFamily;
use arenasim::states::play_match::abilities::AbilityType;
use arenasim::states::play_match::ability_config::{load_ability_definitions, AbilityDefinitions};
use arenasim::states::play_match::equipment::{load_item_definitions, ItemDefinitions, ItemId};
use arenasim::states::play_match::talents::{TalentDefinitions, TalentId};

/// The live item table, restricted to [`ITEMS`].
pub fn items() -> ItemDefinitions {
    load_item_definitions()
        .expect("items.ron must load")
        .restricted_to(ITEMS)
}

/// The live ability table, restricted to [`ABILITIES`].
pub fn abilities() -> AbilityDefinitions {
    load_ability_definitions()
        .expect("abilities.ron must load")
        .restricted_to(ABILITIES)
}

/// The live talent table, restricted to [`TALENTS`] (and the trees holding
/// them).
pub fn talents() -> &'static TalentDefinitions {
    static PINNED: std::sync::OnceLock<TalentDefinitions> = std::sync::OnceLock::new();
    PINNED.get_or_init(|| TalentDefinitions::shipped().restricted_to(TALENTS))
}

