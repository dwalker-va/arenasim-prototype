fn main() {
    // Declare this script's inputs.
    //
    // A build script that prints no `rerun-if-*` directive at all opts into
    // Cargo's documented fallback of treating EVERY file in the package as an
    // input to it. On a non-Windows host this script printed none, so editing
    // a test, a doc or an asset reran it, which invalidated the crate, which
    // rebuilt all 52 test binaries — a documented zero-rebuild `.ron` retune
    // loop cost a full rebuild.
    //
    // The line matters for being PRESENT more than for the path it names:
    // Cargo already reruns the script whenever build.rs itself changes,
    // because the recompiled script binary is a dependency of the run. What
    // the directive buys is switching the fallback off.
    println!("cargo:rerun-if-changed=build.rs");

    // Enable wasm_js for getrandom when building for wasm32.
    //
    // This needs no `rerun-if-env-changed=CARGO_CFG_TARGET_ARCH` to stay
    // correct across a target switch, and adding one would imply a hazard that
    // does not exist. Cargo runs and fingerprints a build script once PER
    // TARGET, into a per-target output directory, so a
    // `--target wasm32-unknown-unknown` build runs this script again and reads
    // its own output — it cannot inherit the host build's cfg, or fail to see
    // the wasm one.
    if std::env::var("CARGO_CFG_TARGET_ARCH").as_deref() == Ok("wasm32") {
        println!("cargo:rustc-cfg=wasm_js");
    }

    embed_windows_icon();

    generate_engine_aura_families();
}

/// The directory whose files are the encyclopedia's engine aura families.
const ENGINE_AURA_FAMILIES_DIR: &str = "src/states/encyclopedia/engine_auras";

/// Generate the engine aura registry from the family files: one module, one
/// `EngineFamily` variant and one dispatch arm per `.rs` file in
/// [`ENGINE_AURA_FAMILIES_DIR`] other than `mod.rs`, which `include!`s the
/// result (see that module's docs).
///
/// Listing the directory is the point: a family is ADDED by adding its file,
/// so two changes that each add one touch no shared line and cannot collide.
/// The variant is the file stem in CamelCase (`frost_trap_slow.rs` is
/// `FrostTrapSlow`), and the families are sorted by stem, so the output is
/// the same on every machine whatever order the filesystem lists them in.
///
/// The directive names the directory, which Cargo scans for any change, so
/// adding, removing or editing a family reruns this — and nothing outside it
/// does.
fn generate_engine_aura_families() {
    use std::fmt::Write as _;

    println!("cargo:rerun-if-changed={ENGINE_AURA_FAMILIES_DIR}");
    let manifest_dir =
        std::path::PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("set by cargo"));
    let dir = manifest_dir.join(ENGINE_AURA_FAMILIES_DIR);
    let mut stems: Vec<String> = std::fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("cannot list {}: {e}", dir.display()))
        .map(|entry| entry.expect("a directory entry").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "rs"))
        .map(|path| {
            path.file_stem()
                .expect("a .rs file has a stem")
                .to_string_lossy()
                .into_owned()
        })
        .filter(|stem| stem != "mod")
        .collect();
    stems.sort();
    for stem in &stems {
        assert!(
            stem.starts_with(|c: char| c.is_ascii_lowercase())
                && stem
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_'),
            "{ENGINE_AURA_FAMILIES_DIR}/{stem}.rs: a family file is named in snake_case \
             (its variant is the CamelCase of the name)"
        );
    }
    let camel = |stem: &str| -> String {
        stem.split('_')
            .map(|word| {
                let mut chars = word.chars();
                chars.next().map_or(String::new(), |first| {
                    first.to_ascii_uppercase().to_string() + chars.as_str()
                })
            })
            .collect()
    };

    let mut out = String::from(
        "// @generated by build.rs (`generate_engine_aura_families`) from the files in\n\
         // src/states/encyclopedia/engine_auras/. Add a family by adding a file there.\n\n",
    );
    // The checkout this was generated for. A build directory shared by two
    // checkouts can hand one the other's file (Cargo keys this script's run on
    // neither path), and its `#[path]`s point into the other tree; the module
    // compares this with its own `CARGO_MANIFEST_DIR` at compile time.
    let _ = writeln!(
        out,
        "/// The checkout this registry was generated for.\npub const GENERATED_FOR: &str = {:?};\n",
        manifest_dir.to_string_lossy()
    );
    for stem in &stems {
        let path = dir.join(format!("{stem}.rs"));
        let _ = writeln!(out, "#[path = {:?}]", path.to_string_lossy());
        let _ = writeln!(out, "pub mod {stem};");
    }
    out.push_str(
        "\n/// One engine aura family per file in this directory, named after it.\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]\n\
         pub enum EngineFamily {\n",
    );
    for stem in &stems {
        let _ = writeln!(out, "    {},", camel(stem));
    }
    out.push_str("}\n\nimpl EngineFamily {\n");
    out.push_str("    /// Every family, in file-name order.\n");
    out.push_str("    pub const ALL: &'static [EngineFamily] = &[\n");
    for stem in &stems {
        let _ = writeln!(out, "        EngineFamily::{},", camel(stem));
    }
    out.push_str("    ];\n\n");
    out.push_str("    /// The name of the file that defines this family, without `.rs`.\n");
    out.push_str("    pub fn file_stem(self) -> &'static str {\n        match self {\n");
    for stem in &stems {
        let _ = writeln!(
            out,
            "            EngineFamily::{} => {stem:?},",
            camel(stem)
        );
    }
    out.push_str("        }\n    }\n\n");
    out.push_str("    /// The members of this family `source` holds (the file's `members`).\n");
    out.push_str(
        "    pub fn members(self, source: &CatalogSource) -> Vec<EngineKey> {\n        match self {\n",
    );
    for stem in &stems {
        let _ = writeln!(
            out,
            "            EngineFamily::{} => {stem}::members(source),",
            camel(stem)
        );
    }
    out.push_str("        }\n    }\n\n");
    out.push_str("    /// The entry `key` resolves to (the file's `entry`).\n");
    out.push_str(
        "    pub fn entry(self, key: EngineKey, source: &CatalogSource) -> Option<EngineSpec> {\n        match self {\n",
    );
    for stem in &stems {
        let _ = writeln!(
            out,
            "            EngineFamily::{} => {stem}::entry(key, source),",
            camel(stem)
        );
    }
    out.push_str("        }\n    }\n\n");
    for (function, constant, kind, doc) in [
        (
            "source_kind",
            "SOURCE",
            "SourceKind",
            "What applies this family's auras",
        ),
        (
            "art_kind",
            "ART",
            "ArtKind",
            "Where this family's icons come from",
        ),
    ] {
        let _ = writeln!(out, "    /// {doc} (the file's `{constant}`).");
        let _ = writeln!(
            out,
            "    pub fn {function}(self) -> {kind} {{\n        match self {{"
        );
        for stem in &stems {
            let _ = writeln!(
                out,
                "            EngineFamily::{} => {stem}::{constant},",
                camel(stem)
            );
        }
        out.push_str("        }\n    }\n\n");
    }
    out.push_str("}\n");

    let out_dir = std::path::PathBuf::from(std::env::var("OUT_DIR").expect("set by cargo"));
    let target = out_dir.join("engine_aura_families.rs");
    // Written only when it changed, so a rerun that finds the same families
    // leaves the file's mtime alone.
    if std::fs::read_to_string(&target).ok().as_deref() != Some(out.as_str()) {
        std::fs::write(&target, out)
            .unwrap_or_else(|e| panic!("cannot write {}: {e}", target.display()));
    }
}

/// Compile the application icon into the Windows executable.
///
/// Windows reads an executable's icon from an embedded resource rather than
/// from a file beside it, so this is what puts the icon on the .exe in Explorer
/// and on the taskbar. macOS takes the opposite approach — the icon is a file
/// inside the .app bundle, named by packaging/macos/Info.plist — so there is
/// nothing to do here for that platform.
///
/// Gated on the HOST rather than the target, matching the `cfg(windows)`
/// build-dependency in Cargo.toml: build-dependency target tables resolve
/// against the host, so the crate simply does not exist on a macOS or Linux
/// build. The release workflow builds Windows on a Windows runner, where host
/// and target agree.
#[cfg(windows)]
fn embed_windows_icon() {
    println!("cargo:rerun-if-changed=packaging/windows/icon.ico");

    let mut resource = winresource::WindowsResource::new();
    resource.set_icon("packaging/windows/icon.ico");
    if let Err(e) = resource.compile() {
        // Not fatal: an iconless build is still a working game, and failing the
        // build over cosmetics would be a poor trade.
        println!("cargo:warning=could not embed the Windows icon: {e}");
    }
}

#[cfg(not(windows))]
fn embed_windows_icon() {}
